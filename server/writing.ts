/** 用户可以自己写结构；没选模版返回空字符串 */
export function templateText(id: unknown, custom: unknown): string {
  const c = typeof custom === 'string' ? custom.trim().slice(0, 1000) : ''
  if (id === 'custom' && c) return `按下面这个结构写：\n${c}`
  const t = TEMPLATES.find((x) => x.id === id)
  return t ? `按「${t.name}」结构写：\n${t.structure}` : ''
}
